#!/usr/bin/env python3
"""Generate the discovery wire DTOs from the checked-in OpenAPI contract."""
import json
from pathlib import Path
import yaml

ROOT = Path(__file__).resolve().parents[1]
SPEC = yaml.safe_load((ROOT / 'docs/contracts/discovery-coffee.openapi.yaml').read_text(encoding='utf-8'))
SCHEMAS = SPEC['components']['schemas']

def cs_type(schema, name='', optional=False):
    if schema.get('type') == 'null':
        return 'object?'
    nullable = optional
    if 'anyOf' in schema:
        nullable = nullable or any(v.get('type') == 'null' for v in schema['anyOf'])
        schema = next(v for v in schema['anyOf'] if v.get('type') != 'null')
    if '$ref' in schema:
        ref = schema['$ref'].rsplit('/', 1)[-1]
        result = ref if SCHEMAS[ref].get('type') == 'object' or 'allOf' in SCHEMAS[ref] else 'string'
    else:
        kind = schema.get('type', 'object')
        if kind == 'array':
            return cs_type(schema['items']) + '[]'
        if kind == 'object':
            if name == 'urls':
                result = 'CoffeePeek.Contract.Dtos.PhotoUrlsDto'
            else:
                result = 'Dictionary<string, ' + cs_type(schema.get('additionalProperties', {'type':'string'})) + '>'
        elif kind == 'string':
            result = {'uuid':'Guid', 'date-time':'DateTime'}.get(schema.get('format'), 'string')
        elif kind == 'integer':
            result = 'long' if name in ('version', 'revision') else 'int'
        elif kind == 'number':
            result = 'decimal'
        elif kind == 'boolean':
            result = 'bool'
        else:
            result = 'object'
    return result + ('?' if nullable else '')

def resolved(schema):
    return SCHEMAS[schema['$ref'].rsplit('/',1)[-1]] if '$ref' in schema else schema

header = [ '// Generated by dev/generate-discovery-dtos.py; edit the OpenAPI schemas instead.',
          '#nullable enable', 'using System.ComponentModel.DataAnnotations;',
          'using System.Text.Json.Serialization;', '',
          'namespace CoffeePeek.Contract.Dtos.Discovery;', '' ]
target = ROOT / 'CoffeePeek.Contract/Dtos/Discovery'
target.mkdir(parents=True, exist_ok=True)
for class_name, schema in SCHEMAS.items():
    if schema.get('type') != 'object':
        continue
    lines = header.copy()
    lines += ['[JsonUnmappedMemberHandling(JsonUnmappedMemberHandling.Disallow)]']
    lines += [f'public class {class_name}', '{']
    for key, prop in schema.get('properties', {}).items():
        required = key in schema.get('required', [])
        value = resolved(prop)
        if 'anyOf' in value:
            value = next(v for v in value['anyOf'] if v.get('type') != 'null')
            value = resolved(value)
        nullable = prop.get('type') == 'null' or ('anyOf' in prop and any(v.get('type') == 'null' for v in prop['anyOf']))
        has_default = 'default' in prop
        optional = not required and not has_default and value.get('type') != 'array'
        typ = cs_type(prop, key, optional)
        if required:
            lines += ['    [JsonRequired]']
            if not nullable:
                lines += ['    [Required]']
        if 'maxLength' in value:
            lines += [f'    [StringLength({value["maxLength"]}, MinimumLength = {value.get("minLength", 0)})]']
        if 'pattern' in value:
            pattern = value['pattern'].replace('"','""')
            lines += [f'    [RegularExpression(@"{pattern}")]']
        if 'enum' in value:
            choices = ', '.join(json.dumps(v, ensure_ascii=False) for v in value['enum'])
            lines += [f'    [DiscoveryChoices({choices})]']
        if value.get('type') == 'array':
            lines += [f'    [DiscoveryItems({value.get("maxItems", 1000)}, {value.get("minItems", 0)}, {str(value.get("uniqueItems", False)).lower()})]']
            item = resolved(value['items'])
            if 'enum' in item:
                choices = ', '.join(json.dumps(v, ensure_ascii=False) for v in item['enum'])
                lines += [f'    [DiscoveryChoices({choices})]']
        if value.get('type') in ('integer', 'number') and ('minimum' in value or 'maximum' in value):
            lo = value.get('minimum', -2147483648)
            hi = value.get('maximum', 9223372036854775807 if typ.rstrip('?') == 'long' else 2147483647)
            if value.get('type') == 'integer' and typ.rstrip('?') == 'int':
                lines += [f'    [Range({lo}, {hi})]']
            else:
                operand = 'long' if typ.rstrip('?') == 'long' else 'decimal'
                lines += [f'    [Range(typeof({operand}), "{lo}", "{hi}")]']
        initializer = ''
        if has_default:
            d = prop['default']
            initializer = ' = ' + ('[' + ', '.join(json.dumps(v) for v in d) + ']' if isinstance(d, list) else json.dumps(d)) + ';'
        elif typ.endswith('[]'):
            initializer = ' = [];'
        elif typ == 'string':
            initializer = ' = string.Empty;'
        elif not typ.endswith('?') and typ not in ('int','long','decimal','bool','Guid','DateTime'):
            initializer = ' = new();'
        lines += [f'    public {typ} {key[0].upper()+key[1:]} {{ get; set; }}{initializer}']
    lines += ['}', '']
    (target / (class_name + '.cs')).write_text('\n'.join(lines), encoding='utf-8', newline='\n')
